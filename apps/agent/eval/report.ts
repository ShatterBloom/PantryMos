// Renders a run as docs/eval-log.md: generated output, not a planning document (§9.4).
import type { Verdict } from './checks.ts';
import { type CaseResult, passed } from './harness.ts';

export interface RunInfo {
  startedAt: Date;
  modelId: string;
  commit: string;
  /** Runs per case; a case passes the run only if every repeat passed. */
  repeat: number;
}

const MARK: Record<Verdict, string> = { pass: '✅', fail: '❌', unverified: '❔' };
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderReport(info: RunInfo, results: readonly CaseResult[]): string {
  const ids = [...new Set(results.map((r) => r.id))];
  const runsOf = (id: string) => results.filter((r) => r.id === id);
  const fullyPassed = ids.filter((id) => runsOf(id).every(passed));
  const lines = [
    '# Eval log',
    '',
    'Generated by `pnpm eval` (apps/agent/eval); do not edit by hand. Checks per IMPLEMENTATION_PLAN §9.4:',
    'tool selection, arguments, DB result, reply consistency. ✅ pass · ❌ fail · ❔ unverified (counts as not passed).',
    '',
    `- Run: ${info.startedAt.toISOString()} · commit \`${info.commit}\` · model \`${info.modelId}\` · ${info.repeat} run(s) per case`,
    `- Passed: **${fullyPassed.length} / ${ids.length}** cases`,
    '',
    '| Case | Run | Tools | Args | DB | Reply | Model calls | Bedrock s | Total s |',
    '|---|---|---|---|---|---|---|---|---|',
  ];
  for (const id of ids) {
    runsOf(id).forEach((r, i) => {
      const { tools, args, db, reply } = r.checks;
      const name = i === 0 ? `${r.id} ${cell(r.title)}${r.aborted ? ' (aborted)' : ''}` : '';
      lines.push(
        `| ${name} | ${i + 1} | ${MARK[tools.verdict]} | ${MARK[args.verdict]} | ${MARK[db.verdict]} | ${MARK[reply.verdict]} | ${r.latency.modelCalls} | ${secs(r.latency.modelMs)} | ${secs(r.latency.totalMs)} |`,
      );
    });
  }
  lines.push('', latency(results), '');

  for (const r of results) {
    lines.push(`## ${r.id} ${r.title}${runsOf(r.id).length > 1 ? ` (run ${runsOf(r.id).indexOf(r) + 1})` : ''}`, '');
    if (r.aborted) lines.push(`**Aborted:** ${r.aborted.split('\n')[0]}`, '');
    for (const [name, check] of Object.entries(r.checks)) {
      for (const note of check.notes) lines.push(`- ${MARK[check.verdict]} ${name}: ${note}`);
    }
    if (Object.values(r.checks).some((c) => c.notes.length > 0)) lines.push('');
    lines.push(`Tools: ${r.calls.map((c) => `${c.name}${c.status === 'error' ? ' (error)' : ''}`).join(' → ') || 'none'}`, '');
    for (const t of r.turns) {
      lines.push(`> **User:** ${t.input}`);
      for (const reply of t.replies) lines.push(`> **Mos:** ${reply}`);
      lines.push('>');
    }
    if (lines.at(-1) === '>') lines.pop();
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

/** §9.9: end-to-end turn latency, Bedrock's share reported separately. */
function latency(results: readonly CaseResult[]): string {
  const turns = results.flatMap((r) => r.turns.map((t) => t.ms)).sort((a, b) => a - b);
  const model = results.reduce((s, r) => s + r.latency.modelMs, 0);
  const total = results.reduce((s, r) => s + r.latency.totalMs, 0);
  if (turns.length === 0) return 'Latency: no turns.';
  const pct = (p: number) => secs(turns[Math.min(turns.length - 1, Math.ceil((p / 100) * turns.length) - 1)]!);
  const share = total > 0 ? Math.round((model / total) * 100) : 0;
  return `Latency per user action (turn plus the proactive work it set off): p50 ${pct(50)} s, p95 ${pct(95)} s over ${turns.length}; Bedrock ${share}% of the total.`;
}

const secs = (ms: number) => (ms / 1000).toFixed(1);
